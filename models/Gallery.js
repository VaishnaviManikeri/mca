const mongoose = require('mongoose');

const gallerySchema = new mongoose.Schema({
  title: {
    type: String,
    required: true
  },
  imageUrl: {
    type: String,
    required: true
  },
  cloudinaryId: {
    type: String,
    required: true
  },
  description: String,
  category: String
}, { timestamps: true });

module.exports = mongoose.model('Gallery', gallerySchema);